const UI_NODE_TEXT=new WeakMap();
const UI_NODE_ATTRIBUTES=new WeakMap();
function uiText(value,language=uiLanguage){
 let text=String(value),trim=text.trim(),canonical=trim;
 // Counts and accessible labels contain original song names; only their interface prefix changes.
 const patterns=[
  [/^Караоке-записей: (\d+)$/,/^הקלטות קריוקי: (\d+)$/,n=>'Караоке-записей: '+n,n=>'הקלטות קריוקי: '+n],
  [/^(\d+) караоке-записей в категории$/,/^(\d+) הקלטות קריוקי בקטגוריה$/,n=>n+' караоке-записей в категории',n=>n+' הקלטות קריוקי בקטגוריה'],
  [/^(\d+) подраздел(?:а|ов)?$/,/^(\d+) מדורים$/,n=>n+([2,3,4].includes(+n)?' подраздела':' подразделов'),n=>n+' מדורים'],
  [/^Избранное: (.*)$/,/^מועדפים: (.*)$/,n=>'Избранное: '+n,n=>'מועדפים: '+n],
  [/^Добавить в очередь: (.*)$/,/^הוספה לתור: (.*)$/,n=>'Добавить в очередь: '+n,n=>'הוספה לתור: '+n],
  [/^Убрать из очереди: (.*)$/,/^הסרה מהתור: (.*)$/,n=>'Убрать из очереди: '+n,n=>'הסרה מהתור: '+n]
 ];
 for(const [ru,he,toRu,toHe] of patterns){const match=trim.match(ru)||trim.match(he);if(match)return language==='he'?toHe(match[1]):toRu(match[1])}
 if(language==='he'&&UI_HE[canonical])return text.replace(trim,UI_HE[canonical]);
 if(language==='ru')return text;
 // Compound headings and navigation labels keep category and performer names intact.
 for(const key of ['Сборник хитов','Поём вместе']){const he=UI_HE[key];text=language==='he'?text.replace(key,he):text.replace(he,key)}
 if(language==='he'){
  text=text.replace(/(\d+) ПОДРАЗДЕЛОВ/g,'$1 מדורים').replace('ВАШИ ИСПОЛНИТЕЛИ','המבצעים שלכם').replace('АНГЛОЯЗЫЧНЫЙ РОК','רוק באנגלית').replace('РУССКАЯ ЭСТРАДА','מוזיקה קלה ברוסית').replace('ДЖАЗ И СВИНГ','ג׳אז וסווינג').replace('АНГЛОЯЗЫЧНЫЙ ПОП','פופ באנגלית').replace('АВТОРСКАЯ ПЕСНЯ','שירי יוצרים');
 }
 return text;
}
function applyUiLanguage(){
 document.documentElement.lang=uiLanguage;document.documentElement.dir=uiLanguage==='he'?'rtl':'ltr';
 const picker=document.querySelector('#ui-language');if(picker)picker.value=uiLanguage;
 const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
 let node;while(node=walker.nextNode()){
  if(!node.parentElement||node.parentElement.closest('script,style,[data-original],.language-picker'))continue;
  let saved=UI_NODE_TEXT.get(node);if(!saved||saved.last!==node.nodeValue)saved={original:node.nodeValue};
  node.nodeValue=uiText(saved.original);saved.last=node.nodeValue;UI_NODE_TEXT.set(node,saved);
 }
 for(const element of document.querySelectorAll('[aria-label],[placeholder]')){
  if(element.closest('.language-picker'))continue;
  let saved=UI_NODE_ATTRIBUTES.get(element)||{};
  for(const attr of ['aria-label','placeholder'])if(element.hasAttribute(attr)){const value=element.getAttribute(attr);if(!saved[attr]||saved[attr].last!==value)saved[attr]={original:value};element.setAttribute(attr,uiText(saved[attr].original));saved[attr].last=element.getAttribute(attr)}
  UI_NODE_ATTRIBUTES.set(element,saved);
 }
 document.title=uiText(document.title);
}
